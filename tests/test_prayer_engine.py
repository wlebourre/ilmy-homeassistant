def _fmt(dt):
    return None if dt is None else dt.strftime("%H:%M")


class TestGoParity(unittest.TestCase):
    """Every generated Go vector must match minute-exact."""

    def test_vectors(self):
        for loc, ymd, method, asr, highlat, *expected in VECTORS:
            with self.subTest(loc=loc, date=ymd, method=method, asr=asr, highlat=highlat):
                lat, lng, tz = LOCS[loc]
                y, m, d = map(int, ymd.split("-"))
                pt = compute_prayer_times(
                    date(y, m, d), lat, lng, tz,
                    method=method, asr_factor=asr, high_latitude=highlat,
                )
                got = tuple(_fmt(getattr(pt, f)) for f in FIELDS)
                self.assertEqual(got, tuple(expected))

    def test_vector_count(self):
        # 760 base + 304 Tromsø high-lat + 24 McMurdo + 64 Hanafi-Asr subset
        self.assertEqual(len(VECTORS), 1152)


class TestResultDatetimes(unittest.TestCase):
    def test_timezone_aware_and_localised(self):
        pt = compute_prayer_times(
            date(2026, 1, 15), 21.4225, 39.8262, "Asia/Riyadh", "mwl"
        )
        tz = ZoneInfo("Asia/Riyadh")
        for f in FIELDS:
            dt = getattr(pt, f)
            with self.subTest(field=f):
                self.assertIsNotNone(dt.tzinfo)
                self.assertEqual(dt.utcoffset(), tz.utcoffset(dt.replace(tzinfo=None)))

    def test_minute_precision(self):
        pt = compute_prayer_times(
            date(2026, 3, 20), 51.5074, -0.1278, "Europe/London", "mwl"
        )
        for f in FIELDS:
            dt = getattr(pt, f)
            if dt is not None:
                self.assertEqual((dt.second, dt.microsecond), (0, 0))

    def test_rollover_to_next_day(self):
        # London summer MWL Isha lands after midnight UTC, so the instant
        # rolls into the next civil date — same normalisation as Go's
        # time.Date arithmetic.
        pt = compute_prayer_times(
            date(2026, 6, 21), 51.5074, -0.1278, "Europe/London", "mwl"
        )
        self.assertIsNotNone(pt.midnight)
        self.assertGreaterEqual(pt.midnight.date(), date(2026, 6, 21))
        self.assertLessEqual(pt.midnight.date(), date(2026, 6, 23))

    def test_polar_none_without_highlat(self):
        # Tromsø midnight sun: Fajr/Sunrise/Maghrib/Isha are not computable
        # and high_latitude=0 applies no adjustment (Go's zero time).
        pt = compute_prayer_times(
            date(2026, 6, 21), 69.6492, 18.9553, "Europe/Oslo", "mwl"
        )
        self.assertIsNone(pt.fajr)
        self.assertIsNone(pt.sunrise)
        self.assertIsNone(pt.maghrib)
        self.assertIsNone(pt.isha)
        self.assertIsNotNone(pt.dhuhr)
        self.assertIsNotNone(pt.asr)
        # Midnight falls back to solar midnight (dhuhr + 12h).
        self.assertEqual(pt.midnight - pt.dhuhr, timedelta(hours=12))


class TestValidation(unittest.TestCase):
    def test_invalid_method(self):
        for bad in ("", "MWL", "nope", "mwl "):
            with self.subTest(method=bad):
                with self.assertRaises(PrayerTimesError):
                    compute_prayer_times(
                        date(2026, 1, 15), 21.4, 39.8, "Asia/Riyadh", bad
                    )

    def test_invalid_asr_factor(self):
        for bad in (0, 3, -1):
            with self.subTest(asr=bad):
                with self.assertRaises(PrayerTimesError):
                    compute_prayer_times(
                        date(2026, 1, 15), 21.4, 39.8, "Asia/Riyadh", "mwl",
                        asr_factor=bad,
                    )

    def test_invalid_high_latitude(self):
        for bad in (-1, 4, 99):
            with self.subTest(highlat=bad):
                with self.assertRaises(PrayerTimesError):
                    compute_prayer_times(
                        date(2026, 1, 15), 21.4, 39.8, "Asia/Riyadh", "mwl",
                        high_latitude=bad,
                    )

    def test_error_is_value_error(self):
        self.assertTrue(issubclass(PrayerTimesError, ValueError))

    def test_invalid_timezone(self):
        with self.assertRaises(ValueError):
            compute_prayer_times(
                date(2026, 1, 15), 21.4, 39.8, "Not/AZone", "mwl"
            )


